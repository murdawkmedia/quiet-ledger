import {test,expect} from '@playwright/test';
import {startMerchantBillingFixture,merchantBillingOwnerToken} from '../merchant-billing-app.js';
import type {Invoice} from '../../shared/contracts.js';

// Built application, real owner session/CSRF, Express routes and temporary SQLite.
// All financial figures and identities are fictional. No payment is requested.
test('saved draft reload, issue and next-month duplicate preserve original records and exclude reviewed expenses',async({page},info)=>{
  const fixture=await startMerchantBillingFixture(),errors:string[]=[];
  page.on('pageerror',error=>errors.push(error.message));
  try{
    await page.goto(fixture.origin);
    await page.getByRole('button',{name:'I have an owner token',exact:true}).click();
    await page.getByLabel('Owner token',{exact:true}).fill(merchantBillingOwnerToken);
    await page.getByRole('button',{name:'Open private workspace',exact:true}).click();
    await page.getByRole('link',{name:'Create invoice',exact:true}).first().click();
    await page.getByLabel('Customer name',{exact:true}).fill('Fictional Monthly Studio');
    await page.getByLabel('Invoice title',{exact:true}).fill('Fictional first month with travel');
    await page.getByLabel('Payment schedule',{exact:true}).selectOption('30');
    await page.getByLabel('Tax rate (%)',{exact:true}).fill('0');
    await page.getByLabel('Item 1 description',{exact:true}).fill('Fictional monthly services');
    await page.getByLabel('Item 1 unit price',{exact:true}).fill('1000.00');
    await page.getByRole('button',{name:'Add line item',exact:true}).click();
    await page.getByLabel('Item 2 description',{exact:true}).fill('Fictional one-off flight');
    await page.getByLabel('Item 2 unit price',{exact:true}).fill('400.00');
    await page.getByLabel('Item 2 type',{exact:true}).selectOption('expense');
    await page.getByRole('button',{name:'Add method price rule',exact:true}).click();
    await page.getByLabel('Rule 1 method',{exact:true}).selectOption('bitcoin');
    await page.getByLabel('Rule 1 discount (%)',{exact:true}).fill('15');
    await expect(page.getByTestId('draft-save-status-text')).toContainText('Draft saved');
    await expect(page).toHaveURL(/\/drafts\/[0-9a-f-]{36}$/);
    const originalDraft=page.url().split('/').at(-1)!;
    expect((await(await page.request.get(fixture.origin+'/api/invoices')).json()).invoices).toHaveLength(0);
    await page.reload();
    await expect(page.getByLabel('Invoice title',{exact:true})).toHaveValue('Fictional first month with travel');
    await expect(page.getByLabel('Item 2 apply discounts/premiums',{exact:true})).not.toBeChecked();
    await expect(page.locator('.method-price-preview')).toContainText('1,250.00');
    await page.getByRole('button',{name:'Create invoice',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Invoices, kept simple.',exact:true})).toBeVisible();
    const first:Invoice=(await(await page.request.get(fixture.origin+'/api/invoices')).json()).invoices[0];
    expect(first.total).toBe(140000);
    expect(first.methodPricing).toEqual([{method:'bitcoin',discountBps:1500}]);
    expect(first.items[1]).toMatchObject({kind:'expense',adjustmentEligible:false});
    const issued=(await(await page.request.get(fixture.origin+'/api/invoice-drafts/'+originalDraft)).json()).draft;
    expect(issued.status).toBe('issued');expect(issued.invoiceId).toBe(first.id);
    await page.getByRole('link',{name:'Duplicate',exact:true}).first().click();
    await expect(page.getByTestId('carried-expense-review')).toBeVisible();
    await expect(page.getByRole('button',{name:'Create invoice',exact:true})).toBeDisabled();
    await page.getByRole('button',{name:'Remove carried expenses',exact:true}).click();
    await expect(page.getByLabel('Item 2 description',{exact:true})).toHaveCount(0);
    await page.getByLabel('Invoice title',{exact:true}).fill('Fictional next month without travel');
    await page.getByLabel('Issue date',{exact:true}).fill('2027-03-01');
    await expect(page.getByText('Due 2027-03-31',{exact:false})).toBeVisible();
    await expect(page.getByTestId('draft-save-status-text')).toContainText('Draft saved');
    expect(page.url().split('/').at(-1)).not.toBe(originalDraft);
    await page.getByRole('button',{name:'Create invoice',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Invoices, kept simple.',exact:true})).toBeVisible();
    const invoices:Invoice[]=(await(await page.request.get(fixture.origin+'/api/invoices')).json()).invoices;
    expect(invoices).toHaveLength(2);
    expect(invoices.find(row=>row.id===first.id)).toEqual(first);
    const next=invoices.find(row=>row.id!==first.id)!;
    expect(next).toMatchObject({total:100000,issueDate:'2027-03-01',dueDate:'2027-03-31',paymentTermDays:30,methodPricing:first.methodPricing});
    expect(next.items).toHaveLength(1);expect(next.id).not.toBe(first.id);expect(next.token).not.toBe(first.token);
    await page.setViewportSize({width:390,height:844});
    await page.goto(fixture.origin+'/drafts');
    await expect(page.getByTestId('saved-draft-row')).toHaveCount(2);
    await expect(page.getByTestId('saved-draft-discard')).toHaveCount(0);
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    await page.screenshot({path:info.outputPath('fictional-monthly-drafts-mobile.png'),fullPage:true});
    expect(errors).toEqual([]);
  }finally{await fixture.close();}
});

// Built UI -> real API -> encrypted SQLite -> synthetic bank adapter. Both rule bases
// (eligible labour and whole-invoice subtotal), the all-fiat group fallback rule, a
// concrete bank confirmation at the fictional 294000 premium price, reload immutability
// and a duplicate that preserves the group rule and its basis. All figures fictional;
// no funded payment, email or external network action.
test('fiat group and eligible bases survive draft reload, bank checkout lock and duplicate',async({page},info)=>{
  const fixture=await startMerchantBillingFixture(),errors:string[]=[];
  page.on('pageerror',error=>errors.push(error.message));
  try{
    await page.goto(fixture.origin);
    await page.getByRole('button',{name:'I have an owner token',exact:true}).click();
    await page.getByLabel('Owner token',{exact:true}).fill(merchantBillingOwnerToken);
    await page.getByRole('button',{name:'Open private workspace',exact:true}).click();
    await page.getByRole('link',{name:'Create invoice',exact:true}).first().click();
    await page.getByLabel('Customer name',{exact:true}).fill('Fictional Fiat Basis Studio');
    await page.getByLabel('Invoice title',{exact:true}).fill('Fictional eligible labour with whole-invoice fiat');
    await page.getByLabel('Payment schedule',{exact:true}).selectOption('30');
    await page.getByLabel('Tax rate (%)',{exact:true}).fill('0');
    await page.getByLabel('Item 1 description',{exact:true}).fill('Fictional eligible services');
    await page.getByLabel('Item 1 unit price',{exact:true}).fill('2000.00');
    await page.getByRole('button',{name:'Add line item',exact:true}).click();
    await page.getByLabel('Item 2 description',{exact:true}).fill('Fictional excluded flights');
    await page.getByLabel('Item 2 unit price',{exact:true}).fill('800.00');
    await page.getByLabel('Item 2 type',{exact:true}).selectOption('expense');
    await page.getByRole('button',{name:'Add method price rule',exact:true}).click();
    await page.getByLabel('Rule 1 method',{exact:true}).selectOption('lightning');
    await page.getByLabel('Rule 1 discount (%)',{exact:true}).fill('15');
    await page.getByRole('button',{name:'Add method price rule',exact:true}).click();
    await page.getByLabel('Rule 2 method',{exact:true}).selectOption('fiat');
    await page.getByLabel('Rule 2 adjustment base',{exact:true}).selectOption('subtotal');
    await page.getByLabel('Rule 2 premium (%)',{exact:true}).fill('5');
    await expect(page.getByTestId('method-preview-lightning')).toContainText('$2,500.00');
    await expect(page.getByTestId('method-preview-fiat')).toContainText('+$140.00');
    await expect(page.getByTestId('method-preview-fiat')).toContainText('$2,940.00');
    await expect(page.getByTestId('draft-save-status-text')).toContainText('Draft saved');
    await expect(page).toHaveURL(/\/drafts\/[0-9a-f-]{36}$/);
    const originalDraft=page.url().split('/').at(-1)!;
    await page.reload();
    await expect(page.getByLabel('Invoice title',{exact:true})).toHaveValue('Fictional eligible labour with whole-invoice fiat');
    await expect(page.getByLabel('Rule 1 method',{exact:true})).toHaveValue('lightning');
    await expect(page.getByLabel('Rule 1 discount (%)',{exact:true})).toHaveValue('15');
    await expect(page.getByLabel('Rule 2 method',{exact:true})).toHaveValue('fiat');
    await expect(page.getByLabel('Rule 2 adjustment base',{exact:true})).toHaveValue('subtotal');
    await expect(page.getByLabel('Rule 2 premium (%)',{exact:true})).toHaveValue('5');
    await expect(page.getByTestId('method-preview-lightning')).toContainText('$2,500.00');
    await expect(page.getByTestId('method-preview-fiat')).toContainText('$2,940.00');
    await expect(page.getByTestId('invoice-total')).toHaveText('$2,800.00');
    const rules=[{method:'lightning',discountBps:1500},{method:'fiat',basis:'subtotal',premiumBps:500}];
    await page.getByRole('button',{name:'Create invoice',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Invoices, kept simple.',exact:true})).toBeVisible();
    const first:Invoice=(await(await page.request.get(fixture.origin+'/api/invoices')).json()).invoices[0];
    expect(first.total).toBe(280000);
    expect(first.methodPricing).toEqual(rules);
    expect(first.items[1]).toMatchObject({kind:'expense',adjustmentEligible:false});
    const issued=(await(await page.request.get(fixture.origin+'/api/invoice-drafts/'+originalDraft)).json()).draft;
    expect(issued.status).toBe('issued');expect(issued.invoiceId).toBe(first.id);
    await page.goto(`${fixture.origin}/pay/${first.token}`);
    const bank=page.getByTestId('price-offer-bank');
    await expect(bank).toContainText('Whole invoice before tax $2,800.00');
    await expect(bank).toContainText('+$140.00');
    await expect(bank).toContainText('$2,940.00');
    await expect(page.getByTestId('price-offer-lightning')).toHaveCount(0);
    await bank.getByRole('button',{name:'Select Bank transfer price',exact:true}).click();
    await page.getByRole('button',{name:'Confirm Bank transfer at $2,940.00',exact:true}).click();
    await expect(page.getByText('Bank transfer price locked',{exact:true})).toBeVisible();
    await expect(page.getByTestId('agreement-basis')).toHaveText('Whole invoice before tax ($2,800.00)');
    await expect(page.getByTestId('agreement-effective-total')).toHaveText('$2,940.00');
    const locked=await(await page.request.get(`${fixture.origin}/api/checkout/${first.token}`)).json();
    expect(locked.invoice.priceAgreement).toMatchObject({method:'bank',basis:'subtotal',effectiveTotal:294000,adjustedSubtotal:294000,premiumAmount:14000,effectiveTax:0,issuedTotal:280000});
    expect(locked.pricingOffers).toEqual([]);
    await page.reload();
    await expect(page.getByText('Bank transfer price locked',{exact:true})).toBeVisible();
    await expect(page.getByTestId('agreement-basis')).toHaveText('Whole invoice before tax ($2,800.00)');
    const relocked=await(await page.request.get(`${fixture.origin}/api/checkout/${first.token}`)).json();
    expect(relocked.invoice.priceAgreement).toEqual(locked.invoice.priceAgreement);
    await page.goto(`${fixture.origin}/invoices/${first.id}/ledger`);
    await expect(page.getByText('Bank transfer price locked',{exact:true})).toBeVisible();
    await expect(page.getByText('Adjustment base',{exact:true})).toBeVisible();
    await expect(page.getByText('Whole invoice before tax ($2,800.00)',{exact:true})).toBeVisible();
    const original:Invoice=(await(await page.request.get(fixture.origin+'/api/invoices')).json()).invoices.find((row:Invoice)=>row.id===first.id)!;
    await page.goto(fixture.origin+'/invoices');
    await page.getByRole('link',{name:'Duplicate',exact:true}).first().click();
    await expect(page.getByTestId('carried-expense-review')).toBeVisible();
    await expect(page.getByRole('button',{name:'Create invoice',exact:true})).toBeDisabled();
    await expect(page.getByLabel('Rule 1 method',{exact:true})).toHaveValue('lightning');
    await expect(page.getByLabel('Rule 1 discount (%)',{exact:true})).toHaveValue('15');
    await expect(page.getByLabel('Rule 2 method',{exact:true})).toHaveValue('fiat');
    await expect(page.getByLabel('Rule 2 adjustment base',{exact:true})).toHaveValue('subtotal');
    await expect(page.getByLabel('Rule 2 premium (%)',{exact:true})).toHaveValue('5');
    await expect(page.getByTestId('method-preview-fiat')).toContainText('$2,940.00');
    await page.getByTestId('carried-expense-ack').check();
    await page.getByLabel('Invoice title',{exact:true}).fill('Fictional duplicate with the same rules');
    await page.getByLabel('Issue date',{exact:true}).fill('2027-04-01');
    await expect(page.getByText('Due 2027-05-01',{exact:false})).toBeVisible();
    await expect(page.getByTestId('draft-save-status-text')).toContainText('Draft saved');
    expect(page.url().split('/').at(-1)).not.toBe(originalDraft);
    await page.getByRole('button',{name:'Create invoice',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Invoices, kept simple.',exact:true})).toBeVisible();
    const invoices:Invoice[]=(await(await page.request.get(fixture.origin+'/api/invoices')).json()).invoices;
    expect(invoices).toHaveLength(2);
    expect(invoices.find(row=>row.id===first.id)).toEqual(original);
    const next=invoices.find(row=>row.id!==first.id)!;
    expect(next).toMatchObject({total:280000,issueDate:'2027-04-01',dueDate:'2027-05-01',paymentTermDays:30,methodPricing:rules});
    expect(next.items).toHaveLength(2);
    expect(next.priceAgreement).toBeUndefined();
    expect(next.id).not.toBe(first.id);expect(next.token).not.toBe(first.token);
    const nextCheckout=await(await page.request.get(`${fixture.origin}/api/checkout/${next.token}`)).json();
    expect(nextCheckout.invoice.priceAgreement).toBeUndefined();
    expect(nextCheckout.pricingOffers.map((offer:{method:string})=>offer.method)).toEqual(['bank']);
    expect(errors).toEqual([]);
  }finally{await fixture.close();}
});
